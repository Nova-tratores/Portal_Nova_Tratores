begin;

create table if not exists frota_os (
  id               uuid primary key default gen_random_uuid(),
  numero           bigint generated by default as identity unique,   -- "OS-F 12"
  veiculo_id       uuid not null references frota_veiculos(id) on delete cascade,
  placa            text not null,
  etapa            text not null default 'aberta'
                   check (etapa in ('aberta','em_oficina','aguardando_peca','pronta','concluida','cancelada')),
  etapa_desde      timestamptz not null default now(),
  descricao        text,
  oficina          text not null default 'propria' check (oficina in ('propria','externa')),
  fornecedor       text,                 -- oficina externa
  os_pos           text,                 -- nº da OS do Pós (oficina própria)
  imobiliza        boolean not null default true,   -- carro fica parado enquanto está na oficina
  -- entrada na oficina
  km_entrada       integer,
  foto_entrada     text,
  entrada_em       timestamptz,
  -- aguardando peça (a última; o histórico fica nos eventos)
  peca             text,
  previsao_peca    date,
  -- pronta / entregue
  pronta_em        timestamptz,
  km_saida         integer,
  foto_saida       text,
  retirado_por     text,
  concluida_em     timestamptz,
  cancelada_motivo text,
  requisicao_id    bigint,               -- "Requisicao".id criada pelo botão da OS
  criado_por       text,
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now()
);
-- uma OS ativa por carro (a segunda vira item da primeira)
create unique index if not exists uq_frota_os_ativa on frota_os (veiculo_id)
  where etapa not in ('concluida','cancelada');
create index if not exists idx_frota_os_etapa on frota_os (etapa, etapa_desde);

create table if not exists frota_os_itens (
  id            uuid primary key default gen_random_uuid(),
  os_id         uuid not null references frota_os(id) on delete cascade,
  tipo          text not null check (tipo in ('pendencia','preventiva','avulso')),
  pendencia_id  uuid references frota_pendencias(id) on delete set null,
  plano_id      uuid references frota_planos(id) on delete set null,
  descricao     text not null,
  feito         boolean not null default false,
  feito_em      timestamptz,
  feito_por     text,
  foto_url      text,
  obs           text,
  criado_em     timestamptz not null default now()
);
create index if not exists idx_frota_os_itens_os on frota_os_itens (os_id);
create unique index if not exists uq_frota_os_itens_pend on frota_os_itens (os_id, pendencia_id) where pendencia_id is not null;
create unique index if not exists uq_frota_os_itens_plano on frota_os_itens (os_id, plano_id) where plano_id is not null;

create table if not exists frota_os_eventos (
  id        uuid primary key default gen_random_uuid(),
  os_id     uuid not null references frota_os(id) on delete cascade,
  de        text,
  para      text not null,
  quem      text,
  em        timestamptz not null default now(),
  detalhe   jsonb
);
create index if not exists idx_frota_os_eventos_os on frota_os_eventos (os_id, em);

-- frota_servicos aceita origem 'os' desde sql/frota-preventiva.sql (o item de
-- preventiva feito na OS registra o serviço com origem_ref = id da OS).

do $$
declare t text;
begin
  foreach t in array array['frota_os','frota_os_itens','frota_os_eventos']
  loop
    execute format('alter table %I enable row level security;', t);
    execute format('drop policy if exists %I on %I;', t || '_select', t);
    execute format('create policy %I on %I for select to authenticated using (public.portal_pode_frota());', t || '_select', t);
    execute format('revoke all on %I from anon;', t);
    execute format('revoke insert, update, delete on %I from authenticated;', t);
    execute format('grant select on %I to authenticated;', t);
  end loop;
end $$;

commit;

notify pgrst, 'reload schema';
