--   - tabela própria (não é ticket nem grupo de pendências);
--   - etapas: aberta → em_oficina → aguardando_peca ⇄ em_oficina → pronta →
--     concluida (cancelada a partir de qualquer etapa ativa);
--   - entrar na oficina pede km com foto; aguardando peça pede qual peça e a
--     previsão; concluir pede km de saída com foto e quem retirou;
--   - quem move é o pós-vendas; quem tem a Frota abre a OS;
--   - o carro conta como PARADO de "em oficina" até "pronta" (imobiliza).
--
-- Idempotente. Sem esta migration a tela /frota/oficina mostra "falta aplicar
-- sql/frota-oficina.sql" e nada mais quebra (a rota devolve migracaoFaltando).
-- RLS no padrão da Fase 0: leitura com o módulo Frota, escrita só pelas rotas
-- (service role).
