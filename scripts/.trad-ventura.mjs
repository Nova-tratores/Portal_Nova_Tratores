const ROM = { 'Ⅰ': ' I', 'Ⅱ': ' II', 'Ⅲ': ' III' }
const stripPrefixo = (s) => s.replace(/^[A-Z]{0,3}\d+[a-z]?(?:-\d+)?\s+/i, '').trim()
function traduzir(nome) {
  let core = stripPrefixo(nome).replace(/[ⅠⅡⅢ]/g, (c) => ROM[c]).replace(/\s+/g, ' ').trim()
  const romano = (core.match(/\b(I{1,3})\b\s*$/) || [])[1] || ''
  let base = core.replace(/\b(I{1,3})\b\s*$/, '').trim()
  const m = base.match(/^([^(（]+?)\s*[(（](.+)$/)
  let quals = ''
  if (m) { quals = m[2].replace(/[)）]\s*$/, '').trim(); base = m[1].trim() }
  base = base.replace(/[.，,]+$/, '').replace(/\s+/g, ' ').trim().toUpperCase()
  const basePT = BASE[base]
  if (!basePT) return null
  let out = basePT
  if (romano) out += ' ' + romano
  if (quals) { let q = quals; for (const [re, pt] of QUAL) q = q.replace(re, pt); out += ` (${q})` }
  return out
}

let ok = 0; const nt = new Set()
for (const modelo of MODS) {
  const { data: figs } = await sb.from('catalogo_figuras').select('id,name').eq('modelo', modelo)
  for (const f of figs) {
    if (/[À-ÿ]/.test(f.name) && !/[A-Z]{3}/.test(stripPrefixo(f.name))) continue
    const pt = traduzir(f.name)
    if (!pt) { if (/[a-zA-Z]{3}/.test(f.name)) nt.add(f.name); continue }
    if (pt !== f.name) { await sb.from('catalogo_figuras').update({ name: pt }).eq('id', f.id); ok++ }
  }
  await sb.from('catalogo_figuras').update({ secao: 'VEÍCULO' }).eq('modelo', modelo).eq('secao', 'VEICULO')
}
console.log(`✅ ${ok} figuras traduzidas`)
